"""Every unit a mod may field — from the places a unit descriptor lives.

``Deck.ndfbin`` is the wrong place to ask this question.  It only knows the
units some deck *already fields*: measured on Test, 2100 of them, out of 2898
the base game defines.  So a modder who wanted to put a vanilla ``Su_27K_SOV``
into a battalion was refused — the picker was answering "has this file used it
yet?" while the user was asking "does this unit exist?".

It misled in the other direction too.  A workshop mod's own units are declared
in its ``Unit.ndfbin`` and do not appear in ``Deck.ndfbin`` at all until
something fields them, so *A World in Flames*' 788 new units were unreachable
even from its own file.

A unit descriptor lives in one of three places, all of them part of **this
mod's** load order and none of them another mod's:

==================  =====================================================  =====
vanilla             ``<WARNO>/Mods/ModData/base.zip`` →                  2898
                    ``GameData/Generated/Gameplay/Gfx/UniteDescriptor.ndf``
project             ``<WARNO>/Mods/<Name>/GameData/Generated/Gameplay/``  local
                    ``Gfx/UniteDescriptor.ndf``                           only
compiled            ``<mod>/Gen/NDF/GFX/Unit.ndfbin`` — the only form a   3686
                    workshop mod ships; includes the vanilla set plus    (AWF)
                    the mod's own
==================  =====================================================  =====

Running the numbers on the three sources is what makes the picker honest: a
unit is offered when a definition file declares it, and refused only when
nothing in the load order does.
"""

from __future__ import annotations

import re
import zipfile
from dataclasses import dataclass, field
from pathlib import Path

from ..core import cndf_codec
from . import modlocator
from ..i18n import tr

#: ``export Descriptor_Unit_X is TEntityDescriptor`` — every unit descriptor in
#: the game is one of these, in both the text and the compiled form.
_EXPORT_RE = re.compile(r"^\s*export\s+(\S+)\s+is\s+\w+", re.M)

#: The one naming rule.  ``Descriptor_Unit_`` also appears inside longer names
#: (``DamageLevelsPackDescriptor_Unit_packStun``), so the check is on the whole
#: ``$/GFX/Unit/...`` path rather than on the leaf.
UNIT_PATH_RE = re.compile(r"^\$/GFX/Unit/Descriptor_Unit_\w+$")

#: Where the descriptor table lives, inside ``base.zip`` and in a project tree.
UNITE_NDF_ENTRY = "GameData/Generated/Gameplay/Gfx/UniteDescriptor.ndf"

#: The compiled form a mod ships.
UNITE_NDFBIN_REL = Path("Gen") / "NDF" / "GFX" / "Unit.ndfbin"

#: ``ModGen``'s baseline, regenerated by ``UpdateMod`` so it tracks the patch
#: level.  Reading it is how the editor knows the vanilla roster without
#: unpacking the game's own 20 GB of ``ZZ_*.dat`` archives.
BASE_ZIP_REL = Path("Mods") / "ModData" / "base.zip"

#: Reading ``base.zip`` means inflating a 27 MB text file; the caches key on
#: ``(path, mtime, size)`` so a rebuilt file is noticed but a reopened dialog
#: costs nothing.
_CACHE: dict[tuple, frozenset] = {}


def _stat_key(path: Path) -> tuple:
    st = path.stat()
    return (str(path), st.st_mtime_ns, st.st_size)


def _cached(path: Path, reader) -> frozenset[str]:
    try:
        key = _stat_key(path)
    except OSError:
        return frozenset()
    if key not in _CACHE:
        try:
            _CACHE[key] = frozenset(reader(path))
        except Exception:                                   # noqa: BLE001
            # A corrupt archive or an unexpected schema must not take the whole
            # dialog down; the other two sources still answer the question.
            _CACHE[key] = frozenset()
    return _CACHE[key]


def _normalise(names) -> set[str]:
    out = set()
    for name in names:
        path = name if name.startswith("$/") else f"$/GFX/Unit/{name}"
        if UNIT_PATH_RE.match(path):
            out.add(path)
    return out


def units_in_text(text: str) -> set[str]:
    """Unit paths exported by an NDF text source."""
    return _normalise(m for m in _EXPORT_RE.findall(text)
                      if m.startswith("Descriptor_Unit_"))


def units_in_ndfbin(path: Path) -> set[str]:
    """Unit paths exported by a compiled ``Unit.ndfbin``.

    Goes through :func:`~ndfbin_decks.core.cndf_codec.read_exports` rather than
    a full decode: the answer is in the export table, and parsing 56223 objects
    to read a few hundred names took 2 s per mod for nothing.
    """
    exports = cndf_codec.read_exports(Path(path).read_bytes(), str(path))
    return _normalise(exports.values())


def units_in_zip(zip_path: Path) -> set[str]:
    """Unit paths inside a ``base.zip``-style archive."""
    with zipfile.ZipFile(zip_path) as zf:
        entry = next((n for n in zf.namelist()
                      if n.endswith(Path(UNITE_NDF_ENTRY).name)), None)
        if entry is None:
            return set()
        return units_in_text(zf.read(entry).decode("utf-8", errors="ignore"))


def find_base_zip(mod: modlocator.ModPaths | None) -> Path | None:
    """The vanilla baseline archive, if the machine has one.

    The shared ``Mods/ModData/base.zip`` wins over a mod-local ``base.zip``:
    ``UpdateMod`` refreshes the shared one against the installed patch level,
    while a copy sitting next to a mod is a snapshot from whenever that mod was
    last built and can lag a patch behind.  Measured on this machine the two are
    byte-identical (md5 ``3bf3e202…``), but the order still matters the day one
    of them is not.

    A mod-local copy is the fallback for a machine where the shared baseline was
    never generated.
    """
    candidates: list[Path] = [modlocator.warno_root() / BASE_ZIP_REL]
    if mod is not None:
        for base in (mod.project, mod.deploy):
            if base is not None:
                candidates.append(Path(base) / "base.zip")
    for cand in candidates:
        try:
            if cand.is_file():
                return cand
        except OSError:
            continue
    return None


def find_unit_ndfbin(mod: modlocator.ModPaths | None) -> Path | None:
    """This mod's compiled ``Unit.ndfbin``, if it ships one."""
    if mod is None or mod.deploy is None:
        return None
    cand = Path(mod.deploy) / UNITE_NDFBIN_REL
    try:
        return cand if cand.is_file() else None
    except OSError:
        return None


def find_project_units(mod: modlocator.ModPaths | None) -> Path | None:
    """This mod's plaintext ``UniteDescriptor.ndf``, if it has a project tree."""
    if mod is None:
        return None
    roots = [r for r in (mod.project, mod.deploy) if r is not None]
    for root in roots:
        cand = Path(root) / UNITE_NDF_ENTRY
        try:
            if cand.is_file():
                return cand
        except OSError:
            continue
    return None


@dataclass(frozen=True)
class UnitUniverse:
    """The units one mod can field, tagged by where they were declared."""

    vanilla: frozenset[str] = frozenset()
    project: frozenset[str] = frozenset()
    compiled: frozenset[str] = frozenset()
    base_zip: Path | None = None
    unit_ndfbin: Path | None = None
    project_ndf: Path | None = None
    #: paths some pack inside the open ``Deck.ndfbin`` references, whatever
    #: deck kind — the fourth source, and the only one that needs no extra file
    referenced: frozenset[str] = frozenset()

    @property
    def all(self) -> frozenset[str]:
        return self.vanilla | self.project | self.compiled | self.referenced

    def __len__(self) -> int:
        return len(self.all)

    def __contains__(self, path) -> bool:
        return bool(path) and path in self.all

    def knows(self, path: str | None) -> bool:
        return bool(path) and path in self.all

    def origin(self, path: str | None) -> str:
        """``原版`` / ``本mod`` / ``本文件`` / ``""`` for an unknown path."""
        if not path:
            return ""
        if path in self.vanilla:
            return tr("原版")
        if path in self.project or path in self.compiled:
            return tr("本mod")
        if path in self.referenced:
            return tr("本文件")
        return ""

    def summary(self) -> str:
        bits = []
        if self.vanilla:
            bits.append(tr("原版 {v0}", v0=len(self.vanilla)))
        if self.project or self.compiled:
            mine = self.own
            bits.append(tr("本 mod 自有 {v0}", v0=len(mine)))
        if self.referenced:
            bits.append(tr("本文件已引用 {v0}", v0=len(self.referenced)))
        bits.append(tr("合计可选用 {v0}", v0=len(self)))
        return " · ".join(bits)

    @property
    def own(self) -> frozenset[str]:
        """Units this mod declares that the base game does not."""
        return (self.project | self.compiled) - self.vanilla


def build(mod: modlocator.ModPaths | None, *,
          referenced: set[str] | frozenset[str] = frozenset()) -> UnitUniverse:
    """Collect the three definition sources for one mod.

    ``referenced`` is the set the caller already knows from the open
    ``Deck.ndfbin``; passing it in means a mod with neither a project tree nor
    a ``Unit.ndfbin`` (Test and Berlin are both like that) still offers
    everything its own file uses.  ``mod`` may be ``None`` — a loose copy of a
    file — and the shared baseline still applies, because that baseline belongs
    to the install rather than to any one mod.
    """
    base_zip = find_base_zip(mod)
    unit_ndfbin = find_unit_ndfbin(mod)
    project_ndf = find_project_units(mod)

    vanilla = _cached(base_zip, units_in_zip) if base_zip else frozenset()
    compiled = _cached(unit_ndfbin, units_in_ndfbin) if unit_ndfbin else frozenset()
    project = _cached(project_ndf, lambda p: units_in_text(
        Path(p).read_text(encoding="utf-8", errors="ignore"))) \
        if project_ndf else frozenset()

    return UnitUniverse(
        vanilla=vanilla,
        project=project,
        compiled=compiled,
        base_zip=base_zip,
        unit_ndfbin=unit_ndfbin,
        project_ndf=project_ndf,
        referenced=frozenset(referenced),
    )
